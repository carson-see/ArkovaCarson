/** Stable, versioned JSON export schema tag. */
export const CLE_LOG_SCHEMA_VERSION = 'cle_log_v1' as const;

/**
 * Mandatory CLE disclaimer — rendered VERBATIM into the PDF and embedded in the
 * JSON document.
 *
 * Wording note (PR #1034 review, resolved): the original SCRUM-1870 AC draft read
 * "state bar **of accountancy** or bar association". "of accountancy" was a
 * copy-paste artifact from the CPE/NASBA disclaimer (accountancy = CPA, not
 * CLE/attorneys); the correct CLE legal wording is "any state bar or bar
 * association". Corrected here per Carson's review confirmation.
 */
export const CLE_DISCLAIMER_TEXT =
  'This log is generated by Arkova. Arkova is not affiliated with any state bar or bar association. CLE compliance determination remains the responsibility of the licensee and their state bar.';

/**
 * Jurisdiction-informational disclaimer (SCRUM-2379 — CLE-01, Constitution
 * §1.5): jurisdiction tags are informational metadata only. Rendered VERBATIM
 * into the PDF, embedded in the JSON document (`jurisdiction_disclaimer`), and
 * mirrored in the UI copy (`src/lib/copy.ts`
 * `PROFESSIONAL_EDUCATION_S3_LABELS.JURISDICTION_DISCLAIMER` — keep the two in
 * sync). Deliberately avoids any sufficiency/adequacy claim.
 */
export const JURISDICTION_INFORMATIONAL_DISCLAIMER =
  'Jurisdiction tags in this log are informational metadata only. This log does not determine or assert compliance with, or adequacy under, the continuing education requirements of any jurisdiction or licensing body. Compliance determination remains the responsibility of the licensee and their licensing body.';

/**
 * Default Storage bucket for generated exports (overridable via deps).
 * Read from the worker config module (SCRUM-1258 — no ad-hoc process.env
 * reads outside config.ts). `config.exportsStorageBucket` resolves
 * `EXPORTS_STORAGE_BUCKET || 'exports'`, identical to the prior inline read.
 */
const DEFAULT_EXPORTS_BUCKET = config.exportsStorageBucket;

/** Cap records per export to keep generation bounded (perf + memory). Mirrors CPE. */
const MAX_EXPORT_RECORDS = 5000;

const STATE_CODE_SET: ReadonlySet<string> = new Set<string>(US_STATE_CODES);

/**
 * Normalize a caller-supplied jurisdiction to a bare US state code.
 * Accepts a bare code (`CA`, `ca`) or the ISO-3166-2 prefixed form (`US-CA`).
 * Returns the canonical upper-case state code, or null when unrecognised.
 */
export function normalizeJurisdiction(input: unknown): string | null {
  if (typeof input !== 'string') return null;
  let code = input.trim().toUpperCase();
  if (code.startsWith('US-')) code = code.slice(3);
  return STATE_CODE_SET.has(code) ? code : null;
}

// ─── Anchor row shape (worker query projection) ──────
export interface CleExportAnchorRow {
  id: string;
  public_id: string | null;
  org_id: string | null;
  user_id: string | null;
  label: string | null;
  filename: string | null;
  status: string;
  issued_at: string | null;
  chain_timestamp: string | null;
  created_at: string;
  credential_type: string | null;
  metadata: Record<string, unknown> | null;
  cle_metadata: Record<string, unknown> | null;
}

// ─── cle_log_v1 schema (frozen / additive-friendly) ──
/**
 * Per-credential record. Every field is nullable so a partially-extracted
 * anchor still exports cleanly. `extraction_confidence` / `extraction_source`
 * are DELIBERATELY ABSENT — they are internal-only signals, never exported.
 * `ethics_hours` is a SEPARATE field from `credit_hours` (the total) — they are
 * never combined.
 */
export const CleLogRecordSchema = z
  .object({
    public_id: z.string().nullable(),
    title: z.string().nullable(),
    provider: z.string().nullable(),
    provider_approval_status: z.string().nullable(),
    credit_hours: z.number().nullable(),
    ethics_hours: z.number().nullable(),
    jurisdiction: z.string().nullable(),
    delivery_format: z.string().nullable(),
    completion_date: z.string().nullable(),
    verification_url: z.string().nullable(),
    anchor_timestamp: z.string().nullable(),
    evidence_level: z.string().nullable(),
    status: z.string(),
  })
  .strict();

export type CleLogRecord = z.infer<typeof CleLogRecordSchema>;

/**
 * Aggregate summary. `ethics_hours` is a distinct subtotal alongside the total
 * `total_credit_hours` — the AC requires the ethics figure to be shown
 * separately and never merged into the total.
 */
export const CleLogSummarySchema = z
  .object({
    total_credit_hours: z.number(),
    ethics_hours: z.number(),
    approved_provider_hours: z.number(),
    unverified_provider_hours: z.number(),
    hours_by_delivery_format: z.record(z.string(), z.number()),
  })
  .strict();

export type CleLogSummary = z.infer<typeof CleLogSummarySchema>;

export const CleLogV1Schema = z
  .object({
    schema: z.literal(CLE_LOG_SCHEMA_VERSION),
    generated_at: z.string(),
    jurisdiction: z.string(),
    period: z.object({ start: z.string(), end: z.string() }).strict(),
    record_count: z.number().int().nonnegative(),
    /**
     * SCRUM-2378 (CPE-01, mirrored): count of in-period records EXCLUDED
     * because they are not yet SECURED. Additive + optional (§1.8); always
     * emitted for new exports.
     */
    excluded_count: z.number().int().nonnegative().optional(),
    summary: CleLogSummarySchema,
    records: z.array(CleLogRecordSchema),
    disclaimer: z.literal(CLE_DISCLAIMER_TEXT),
    /**
     * SCRUM-2379 (CLE-01): §1.5 jurisdiction-informational disclaimer, verbatim.
     * Additive + optional (§1.8); always emitted for new exports.
     */
    jurisdiction_disclaimer: z.literal(JURISDICTION_INFORMATIONAL_DISCLAIMER).optional(),
  })
  .strict();

export type CleLogV1Document = z.infer<typeof CleLogV1Schema>;

