/**
 * CLE Compliance-Log Export Worker (SCRUM-1870 — CLE-R2)
 *
 * Generates an auditor-ready CLE (Continuing Legal Education) compliance log for
 * an attorney over a reporting period for a specific US state jurisdiction, in
 * both PDF and JSON form, uploads each artifact to Supabase Storage, and returns
 * a short-lived signed URL for each.
 *
 * It also emits a `cle_log.exported` audit event carrying METADATA ONLY
 * (actor, jurisdiction, period, format, record count, request id) — never any
 * export body content (CC7 no-content-leak).
 *
 * Ethics hours are reported as a SEPARATE subtotal in BOTH the PDF summary and
 * the JSON `summary` block — never folded into the total credit-hours figure.
 *
 * Constitution refs:
 *   - 1.4  : never log PII; only public_id + counts. Service-role DB access.
 *   - 1.5  : timestamps in UTC; "Network Observed Time" framing for chain time.
 *   - 1.6  : worker-only — never imports client-side fingerprint code.
 *   - 1.8  : `cle_log_v1` JSON schema is additive/frozen-friendly.
 *
 * Bar framing: this log is informational. Arkova is not affiliated with any
 * state bar; compliance determination stays with the licensee/state bar. The
 * mandatory disclaimer below is rendered verbatim into the PDF and embedded in
 * the JSON document.
 *
 * Reuse: the Supabase Storage seam (`createSupabaseStorageAdapter` /
 * `CpeExportStorage`) is imported from the sibling CPE export module rather than
 * duplicated — the two exports share identical Storage upload/sign semantics.
 */
