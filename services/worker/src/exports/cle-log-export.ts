/**
 * CLE Compliance-Log Export Worker (SCRUM-1870 — CLE-R2)
 *
 * Generates an auditor-ready CLE (Continuing Legal Education) compliance log for
 * an attorney over a reporting period for a specific US state jurisdiction, in
 * both PDF and JSON form, uploads each artifact to Supabase Storage, and returns
 * a short-lived signed URL for each.
 *
 * It also emits a `cle_log.exported` audit event carrying METADATA ONLY
 * (actor, jurisdiction, period, format, record count, request id) — never any
 * export body content (CC7 no-content-leak).
 *
 * Ethics hours are reported as a SEPARATE subtotal in BOTH the PDF summary and
 * the JSON `summary` block — never folded into the total credit-hours figure.
 *
 * Constitution refs:
 *   - 1.4  : never log PII; only public_id + counts. Service-role DB access.
 *   - 1.5  : timestamps in UTC; "Network Observed Time" framing for chain time.
 *   - 1.6  : worker-only — never imports client-side fingerprint code.
 *   - 1.8  : `cle_log_v1` JSON schema is additive/frozen-friendly.
 *
 * Bar framing: this log is informational. Arkova is not affiliated with any
 * state bar; compliance determination stays with the licensee/state bar. The
 * mandatory disclaimer below is rendered verbatim into the PDF and embedded in
 * the JSON document.
 *
 * Reuse: the Supabase Storage seam (`createSupabaseStorageAdapter` /
 * `CpeExportStorage`) is imported from the sibling CPE export module rather than
 * duplicated — the two exports share identical Storage upload/sign semantics.
 */
import { randomUUID } from 'node:crypto';
import { Buffer } from 'node:buffer';
import { jsPDF } from 'jspdf';
import { z } from 'zod';
import type { SupabaseClient } from '@supabase/supabase-js';
import type { Logger } from '../utils/logger.js';
import {
  createSupabaseStorageAdapter,
  SIGNED_URL_TTL_SECONDS,
  type CpeExportStorage,
} from './cpe-log-export.js';
import { US_STATE_CODES } from '../compliance/professional-education.js';

// Re-export the shared Storage seam so callers (and tests) can import either
// from the CLE module or the CPE module without reaching across domains.
export { createSupabaseStorageAdapter, SIGNED_URL_TTL_SECONDS };
export type { CpeExportStorage };

/** Stable, versioned JSON export schema tag. */
export const CLE_LOG_SCHEMA_VERSION = 'cle_log_v1' as const;

/**
 * Mandatory CLE disclaimer — rendered VERBATIM into the PDF and embedded in the
 * JSON document. This is the literal SCRUM-1870 acceptance-criteria text.
 *
 * ⚠️ PO FLAG (see PR body): the AC text says "state bar **of accountancy** or
 * bar association". "of accountancy" appears to be a copy-paste artifact from
 * the CPE/NASBA disclaimer (accountancy = CPA, not CLE/attorneys); the intended
 * legal wording is almost certainly "any state bar or bar association". We
 * implement the AC text verbatim here (the test asserts it) and flag it for
 * Carson to confirm/correct before soak/merge — we do NOT silently reword legal
 * copy.
 */
export const CLE_DISCLAIMER_TEXT =
  'This log is generated by Arkova. Arkova is not affiliated with any state bar of accountancy or bar association. CLE compliance determination remains the responsibility of the licensee and their state bar.';

/** Default Storage bucket for generated exports (overridable via deps/env). */
const DEFAULT_EXPORTS_BUCKET = process.env.EXPORTS_STORAGE_BUCKET || 'exports';

/** Cap records per export to keep generation bounded (perf + memory). Mirrors CPE. */
const MAX_EXPORT_RECORDS = 5000;

const STATE_CODE_SET: ReadonlySet<string> = new Set<string>(US_STATE_CODES);

/**
 * Normalize a caller-supplied jurisdiction to a bare US state code.
 * Accepts a bare code (`CA`, `ca`) or the ISO-3166-2 prefixed form (`US-CA`).
 * Returns the canonical upper-case state code, or null when unrecognised.
 */
export function normalizeJurisdiction(input: unknown): string | null {
  if (typeof input !== 'string') return null;
  let code = input.trim().toUpperCase();
  if (code.startsWith('US-')) code = code.slice(3);
  return STATE_CODE_SET.has(code) ? code : null;
}

// ─── Anchor row shape (worker query projection) ──────
export interface CleExportAnchorRow {
  id: string;
  public_id: string | null;
  org_id: string | null;
  user_id: string | null;
  label: string | null;
  filename: string | null;
  status: string;
  issued_at: string | null;
  chain_timestamp: string | null;
  created_at: string;
  credential_type: string | null;
  metadata: Record<string, unknown> | null;
  cle_metadata: Record<string, unknown> | null;
}

// ─── cle_log_v1 schema (frozen / additive-friendly) ──
/**
 * Per-credential record. Every field is nullable so a partially-extracted
 * anchor still exports cleanly. `extraction_confidence` / `extraction_source`
 * are DELIBERATELY ABSENT — they are internal-only signals, never exported.
 * `ethics_hours` is a SEPARATE field from `credit_hours` (the total) — they are
 * never combined.
 */
export const CleLogRecordSchema = z
  .object({
    public_id: z.string().nullable(),
    title: z.string().nullable(),
    provider: z.string().nullable(),
    provider_approval_status: z.string().nullable(),
    credit_hours: z.number().nullable(),
    ethics_hours: z.number().nullable(),
    jurisdiction: z.string().nullable(),
    delivery_format: z.string().nullable(),
    completion_date: z.string().nullable(),
    verification_url: z.string().nullable(),
    anchor_timestamp: z.string().nullable(),
    evidence_level: z.string().nullable(),
    status: z.string(),
  })
  .strict();

export type CleLogRecord = z.infer<typeof CleLogRecordSchema>;

/**
 * Aggregate summary. `ethics_hours` is a distinct subtotal alongside the total
 * `total_credit_hours` — the AC requires the ethics figure to be shown
 * separately and never merged into the total.
 */
export const CleLogSummarySchema = z
  .object({
    total_credit_hours: z.number(),
    ethics_hours: z.number(),
    approved_provider_hours: z.number(),
    unverified_provider_hours: z.number(),
    hours_by_delivery_format: z.record(z.string(), z.number()),
  })
  .strict();

export type CleLogSummary = z.infer<typeof CleLogSummarySchema>;

export const CleLogV1Schema = z
  .object({
    schema: z.literal(CLE_LOG_SCHEMA_VERSION),
    generated_at: z.string(),
    jurisdiction: z.string(),
    period: z.object({ start: z.string(), end: z.string() }).strict(),
    record_count: z.number().int().nonnegative(),
    summary: CleLogSummarySchema,
    records: z.array(CleLogRecordSchema),
    disclaimer: z.literal(CLE_DISCLAIMER_TEXT),
  })
  .strict();

export type CleLogV1Document = z.infer<typeof CleLogV1Schema>;

