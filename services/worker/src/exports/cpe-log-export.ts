/**
 * CPE Compliance-Log Export Worker (SCRUM-1860 / SCRUM-1848 — CPE-R2)
 *
 * Generates an auditor-ready CPE (Continuing Professional Education) compliance
 * log for a CPA over a reporting period, in both PDF and JSON form, uploads each
 * artifact to Supabase Storage, and returns a short-lived signed URL for each.
 *
 * It also emits a `cpe_log.exported` audit event carrying METADATA ONLY
 * (actor, period, format, record count, request id) — never any export body
 * content (CC7 no-content-leak).
 *
 * Constitution refs:
 *   - 1.4  : never log PII; only public_id + counts. Service-role DB access.
 *   - 1.5  : timestamps in UTC; "Network Observed Time" framing for chain time.
 *   - 1.6  : worker-only — never imports client-side fingerprint code.
 *   - 1.8  : `cpe_log_v1` JSON schema is additive/frozen-friendly.
 *
 * NASBA framing: this log is informational. Arkova is not affiliated with NASBA
 * or any state board; compliance determination stays with the licensee/board.
 * The mandatory disclaimer below is rendered verbatim into the PDF and embedded
 * in the JSON document.
 */
