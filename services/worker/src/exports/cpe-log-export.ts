/** Stable, versioned JSON export schema tag. */
export const CPE_LOG_SCHEMA_VERSION = 'cpe_log_v1' as const;

/**
 * Mandatory NASBA disclaimer — rendered VERBATIM into the PDF and embedded in
 * the JSON document. Do not reword; auditors and the state board rely on this
 * exact non-affiliation statement.
 */
export const NASBA_DISCLAIMER_TEXT =
  'This log is generated by Arkova. Arkova is not affiliated with NASBA or any state board of accountancy. CPE compliance determination remains the responsibility of the licensee and their state board.';

/**
 * Default Storage bucket for generated exports (overridable via deps).
 * Read from the worker config module (SCRUM-1258 — no ad-hoc process.env
 * reads outside config.ts). `config.exportsStorageBucket` resolves
 * `EXPORTS_STORAGE_BUCKET || 'exports'`, identical to the prior inline read.
 */
const DEFAULT_EXPORTS_BUCKET = config.exportsStorageBucket;

/** Signed-URL lifetime: 1 hour. Matches the per-user export cadence. */
export const SIGNED_URL_TTL_SECONDS = 3600;

/** Cap records per export to keep generation bounded (perf + memory). */
const MAX_EXPORT_RECORDS = 5000;

// ─── Anchor row shape (worker query projection) ──────
export interface CpeExportAnchorRow {
  id: string;
  public_id: string | null;
  org_id: string | null;
  user_id: string | null;
  label: string | null;
  filename: string | null;
  status: string;
  issued_at: string | null;
  chain_timestamp: string | null;
  created_at: string;
  credential_type: string | null;
  metadata: Record<string, unknown> | null;
  cpe_metadata: Record<string, unknown> | null;
}

// ─── cpe_log_v1 schema (frozen / additive-friendly) ──
/**
 * Per-credential record. Every field is nullable so a partially-extracted
 * anchor still exports cleanly. `extraction_confidence` / `extraction_source`
 * are DELIBERATELY ABSENT — they are internal-only signals, never exported.
 */
export const CpeLogRecordSchema = z
  .object({
    public_id: z.string().nullable(),
    title: z.string().nullable(),
    provider: z.string().nullable(),
    nasba_status: z.string().nullable(),
    cpe_hours: z.number().nullable(),
    field_of_study: z.string().nullable(),
    delivery_method: z.string().nullable(),
    completion_date: z.string().nullable(),
    verification_url: z.string().nullable(),
    anchor_timestamp: z.string().nullable(),
    evidence_level: z.string().nullable(),
    status: z.string(),
  })
  .strict();

export type CpeLogRecord = z.infer<typeof CpeLogRecordSchema>;

// NOTE (round-1 review): CpeLogRecordSchema/CpeLogV1Schema are INTERNAL-ONLY
// validators — they check OUR OWN generated artifact before upload and are not
// published to external consumers (no SDK/docs export references them). The
// `.strict()` is therefore safe: it can never reject a third party's payload,
// only catch our own drift at generation time. If these schemas are ever
// exported for external parsing, `.strict()` must be revisited (§1.8 additive
// evolution would break strict consumers).
export const CpeLogV1Schema = z
  .object({
    schema: z.literal(CPE_LOG_SCHEMA_VERSION),
    generated_at: z.string(),
    period: z.object({ start: z.string(), end: z.string() }).strict(),
    record_count: z.number().int().nonnegative(),
    /**
     * SCRUM-2378 (CPE-01): count of in-period records EXCLUDED because they are
     * not yet SECURED. Additive + optional (§1.8) so previously-issued
     * documents without the field still validate. Always emitted for new
     * exports — un-SECURED records are excluded, counted, and surfaced; never
     * silently dropped and never blocking the export.
     */
    excluded_count: z.number().int().nonnegative().optional(),
    records: z.array(CpeLogRecordSchema),
    disclaimer: z.literal(NASBA_DISCLAIMER_TEXT),
  })
  .strict();

export type CpeLogV1Document = z.infer<typeof CpeLogV1Schema>;

// ─── Storage adapter (DI — no Storage migration required) ──
/**
 * Thin Storage seam so the worker can be unit-tested without a live Supabase
 * Storage bucket, and so the bucket can be provisioned as an ops step rather
 * than a DB migration (keeps this change T2, not T3).
 */
export interface CpeExportStorage {
  upload(
    bucket: string,
    path: string,
    body: Uint8Array | string,
    contentType?: string,
  ): Promise<{ error: Error | null }>;
  createSignedUrl(
    bucket: string,
    path: string,
    expiresIn: number,
  ): Promise<{ signedUrl: string | null; error: Error | null }>;
  /**
   * Inspect a bucket's existence + visibility. Returns `exists: false` when the
   * bucket is absent so the fail-loud guard can raise a clear error instead of
   * a confusing downstream upload 500, and `isPublic` so a misconfigured PUBLIC
   * bucket — which would expose unsigned export bodies (CC7) — is rejected too.
   */
  getBucket(
    bucket: string,
  ): Promise<{ exists: boolean; isPublic: boolean | null; error: Error | null }>;
}

/** Default Storage adapter backed by the Supabase service-role client. */
export function createSupabaseStorageAdapter(db: SupabaseClient): CpeExportStorage {
  // The generated DB types don't model the Storage API; narrow locally.
  const storage = (db as unknown as { storage: {
    from(bucket: string): {
      upload(path: string, body: Uint8Array | string, opts: { contentType?: string; upsert?: boolean }):
        Promise<{ error: Error | null }>;
      createSignedUrl(path: string, expiresIn: number):
        Promise<{ data: { signedUrl: string } | null; error: Error | null }>;
    };
    getBucket(bucket: string):
      Promise<{ data: { public: boolean } | null; error: Error | null }>;
  } }).storage;

  return {
    async upload(bucket, path, body, contentType) {
      const { error } = await storage
        .from(bucket)
        .upload(path, body, { contentType, upsert: true });
      return { error };
    },
    async createSignedUrl(bucket, path, expiresIn) {
      const { data, error } = await storage.from(bucket).createSignedUrl(path, expiresIn);
      return { signedUrl: data?.signedUrl ?? null, error };
    },
    async getBucket(bucket) {
      const { data, error } = await storage.getBucket(bucket);
      // A missing bucket comes back as `data: null` (often with a "not found"
      // error). Surface existence + visibility; the caller's guard decides.
      return { exists: data != null, isPublic: data?.public ?? null, error };
    },
  };
}

