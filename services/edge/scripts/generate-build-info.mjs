#!/usr/bin/env node
/**
 * SCRUM-3907 / SCRUM-1032 — writes `services/edge/src/build-info.ts` with the
 * real deploy git SHA + timestamp immediately before `wrangler deploy`.
 *
 * Why a generated source file instead of a wrangler `[vars]` entry: a
 * `[vars]` value in `wrangler.toml` is a static string checked into source —
 * there is no wrangler-native way to stamp "the SHA this specific deploy
 * built from" into it without rewriting wrangler.toml on every deploy (and
 * then diffing dirty against git). Writing `src/build-info.ts` instead means
 * the SAME module backs both the deployed `/health` response and local
 * dev/vitest (via the checked-in placeholder `{ git_sha: 'local-dev',
 * built_at: null }`), with no wrangler.toml churn.
 *
 * Usage:
 *   node scripts/generate-build-info.mjs [sha]
 *
 * `sha` defaults to $GITHUB_SHA, then `git rev-parse HEAD`, then 'unknown'.
 * Run from `services/edge/` (matches how `npm run build:info` invokes it).
 */

import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEX_SHA_RE = /^[0-9a-f]{7,40}$/i;

/**
 * Resolve the git SHA to stamp: explicit arg > $GITHUB_SHA > `git rev-parse
 * HEAD` > 'unknown'. Never throws — a resolution failure degrades to
 * 'unknown' rather than failing the deploy over a cosmetic field, but it
 * DOES print a warning so a CI run with a bad SHA is loud in the logs
 * (Builder Contract clause 2: no silent skip).
 */
export function resolveGitSha(explicit) {
  const candidate = explicit || process.env.GITHUB_SHA;
  if (candidate) {
    if (HEX_SHA_RE.test(candidate)) return candidate.toLowerCase();
    console.warn(`::warning::generate-build-info: ignoring non-hex SHA candidate ${JSON.stringify(candidate)}`);
  }
  try {
    const fromGit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    if (HEX_SHA_RE.test(fromGit)) return fromGit.toLowerCase();
  } catch {
    // No .git available (e.g. a tarball build) — fall through to 'unknown'.
  }
  console.warn('::warning::generate-build-info: could not resolve a git SHA; stamping "unknown"');
  return 'unknown';
}

/**
 * Pure render function — the TypeScript source text for `src/build-info.ts`.
 * Kept separate from the CLI/filesystem side so it is unit-testable without
 * touching disk or git. `gitSha` and `builtAt` are trusted to already be
 * validated (hex SHA / ISO string or null) by the caller; this function
 * still defensively re-checks the SHA shape so a bad value can never corrupt
 * the generated TypeScript into something that fails to parse.
 */
export function renderBuildInfoModule(gitSha, builtAt) {
  const safeSha = HEX_SHA_RE.test(gitSha) || gitSha === 'unknown' || gitSha === 'local-dev' ? gitSha : 'unknown';
  const builtAtLiteral = builtAt === null ? 'null' : JSON.stringify(builtAt);
  return `/**
 * Build identity for this Worker bundle.
 *
 * GENERATED by \`services/edge/scripts/generate-build-info.mjs\` — run via
 * \`npm run build:info\` in \`.github/workflows/deploy-edge.yml\` immediately
 * before \`wrangler deploy\`. Do not hand-edit outside the generator.
 */

export interface BuildInfo {
  git_sha: string;
  built_at: string | null;
}

export const BUILD_INFO: BuildInfo = {
  git_sha: ${JSON.stringify(safeSha)},
  built_at: ${builtAtLiteral},
};
`;
}

function main() {
  const explicitSha = process.argv[2];
  const gitSha = resolveGitSha(explicitSha);
  const builtAt = new Date().toISOString();
  const outPath = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'build-info.ts');
  writeFileSync(outPath, renderBuildInfoModule(gitSha, builtAt), 'utf8');
  console.log(`generate-build-info: wrote ${outPath} { git_sha: ${gitSha}, built_at: ${builtAt} }`);
}

// Only run the CLI when invoked directly (`node generate-build-info.mjs`),
// not when imported by the test suite.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main();
}
