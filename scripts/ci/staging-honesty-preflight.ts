/**
 * Check 6 (`prod_divergence`) as a standalone verdict.
 *
 * Split out of buildReport so the report builder stays readable: the
 * baseline-squash-aware path and the legacy strict path are two different
 * judgements that happen to share a check name.
 */
function buildProdDivergenceCheck(
  migrationRows: MigrationRow[],
  prodVersions: string[],
  repoVersions: ReadonlySet<string> | undefined,
  divergence: { missingFromStaging: string[]; extraVsProd: string[] },
): CheckResult {
  if (!repoVersions) {
    const prodDiverged =
      divergence.missingFromStaging.length > 0 || divergence.extraVsProd.length > 0;
    return {
      name: 'prod_divergence',
      passed: !prodDiverged,
      details: prodDiverged
        ? `Missing from staging: [${divergence.missingFromStaging.join(', ')}]; Extra vs prod: [${divergence.extraVsProd.join(', ')}]`
        : 'Staging versions match prod ledger.',
    };
  }

  const verdict = analyzeProdDivergence(migrationRows, prodVersions, repoVersions);
  if (verdict.passed) {
    const subsumed =
      verdict.baselinePresent && verdict.prodMissing.length > 0
        ? ` ${verdict.prodMissing.length} pre-baseline/version-shape prod row(s) subsumed by the canonical baseline (informational).`
        : '';
    return {
      name: 'prod_divergence',
      passed: true,
      details: `Rig ledger reconciles with repo migration files + canonical baseline.${subsumed}`,
    };
  }

  const detailParts: string[] = [];
  if (verdict.unexplainedExtras.length > 0) {
    detailParts.push(`Unexplained extras (not in repo or prod): [${verdict.unexplainedExtras.join(', ')}]`);
  }
  if (verdict.missingRepoMigrations.length > 0) {
    detailParts.push(`Repo migrations missing from rig: [${verdict.missingRepoMigrations.join(', ')}]`);
  }
  if (!verdict.baselinePresent && verdict.prodMissing.length > 0) {
    detailParts.push(`Prod versions missing from rig (no baseline to subsume them): [${verdict.prodMissing.join(', ')}]`);
  }
  return { name: 'prod_divergence', passed: false, details: detailParts.join('; ') };
}

export function buildReport(opts: {
  projectRef: string;
  migrationRows: MigrationRow[];
  submittedAnchorCount: number;
  prodVersions: string[];
  /**
   * Canonical migration versions parsed from supabase/migrations/*.sql (the
   * repo source of truth). When provided, the prod_divergence check becomes
   * baseline-squash-aware via analyzeProdDivergence. When omitted, the legacy
   * strict computeProdDivergence behavior is preserved (any divergence fails).
   */
  repoVersions?: ReadonlySet<string>;
  orgTopology?: OrgTopologyData;
  /**
   * Why the org-topology projection could not be read. When set (and
   * `orgTopology` is not), Check 7 is emitted as a FAILURE rather than
   * omitted — see checkOrgTopologyUnavailable / FD-PREFLIGHT-1.
   */
  orgTopologyError?: string;
  prodFacts?: ProdFactsData;
}): PreflightReport {
  const { projectRef, migrationRows, submittedAnchorCount, prodVersions, repoVersions } = opts;
  const checks: CheckResult[] = [];
  let allArtifactRows: MigrationRow[] = [];

  // Check 1: PR-only / staging-only rows
  const classified = migrationRows
    .map((row) => classifyMigrationRow(row))
    .filter((c): c is ArtifactClassification => c !== null);
  const artifactRowsFromClassification = classified.map((c) => c.row);
  checks.push({
    name: 'staging_only_rows',
    passed: classified.length === 0,
    details: classified.length === 0
      ? 'No PR-only or staging-only migration rows found.'
      : `${classified.length} suspect row(s): ${classified.map((c) => `${c.row.name} (${c.reason})`).join('; ')}`,
  });

  // Check 2: Duplicate names.
  // When repo migration versions are supplied, normalize identity by the numeric
  // version prefix: `supabase db push` stores a rig's names WITHOUT their numeric
  // prefix, so two genuinely-distinct migrations (e.g. 0302 and 0303 of the same
  // descriptive name) collapse to one repeated bare name on the rig. Those are NOT
  // a duplicate. Same-version+same-name replays and prefixed-name collisions are
  // still flagged. Without repoVersions, the legacy bare-name count applies.
  const dupeNames = findDuplicateNames(migrationRows, repoVersions);
  checks.push({
    name: 'duplicate_names',
    passed: dupeNames.length === 0,
    details: dupeNames.length === 0
      ? 'No duplicate migration names.'
      : `Duplicate name(s): ${dupeNames.join(', ')}`,
  });

  // Check 3: Duplicate versions
  const dupeVersions = findDuplicateVersions(migrationRows);
  checks.push({
    name: 'duplicate_versions',
    passed: dupeVersions.length === 0,
    details: dupeVersions.length === 0
      ? 'No duplicate migration versions.'
      : `Duplicate version(s): ${dupeVersions.join(', ')}`,
  });

  // Check 4: Known artifact rows
  const knownArtifacts = detectKnownArtifacts(migrationRows);
  checks.push({
    name: 'known_artifacts',
    passed: knownArtifacts.length === 0,
    details: knownArtifacts.length === 0
      ? 'No known artifact rows.'
      : `${knownArtifacts.length} known artifact(s): ${knownArtifacts.map((r) => r.name).join(', ')}`,
  });

  // Check 5: Missing SUBMITTED anchors
  checks.push({
    name: 'submitted_anchors',
    passed: submittedAnchorCount > 0,
    details: submittedAnchorCount > 0
      ? `${submittedAnchorCount} SUBMITTED anchor(s) found.`
      : 'Zero SUBMITTED anchors — environment may lack test fixtures.',
  });

  // Check 6: Prod divergence.
  // The raw buckets (missingFromStaging / extraVsProd) are always reported for
  // transparency. When the repo migration files are supplied, the PASS/FAIL
  // verdict is baseline-squash-aware (analyzeProdDivergence): legitimacy is
  // judged against repo files + the canonical baseline, never the rig's own
  // claims. Without repoVersions, the legacy strict rule applies (any
  // divergence fails) — this preserves shared-staging behavior.
  const divergence = computeProdDivergence(migrationRows, prodVersions);
  checks.push(
    buildProdDivergenceCheck(migrationRows, prodVersions, repoVersions, divergence),
  );

  // Check 7: Org topology (single-tenant prod vs multi-org staging seeds).
  // An unreadable projection is a FAILED check, never an omitted one.
  if (opts.orgTopology) {
    checks.push(checkOrgTopology(opts.orgTopology));
  } else if (opts.orgTopologyError) {
    checks.push(checkOrgTopologyUnavailable(opts.orgTopologyError));
  }

  // Check 8: Prod facts (pg_cron, function existence, scheduling)
  if (opts.prodFacts) {
    checks.push(checkProdFacts(opts.prodFacts));
  }

  // Collect all artifact rows (deduplicated by version+name).
  const seen = new Set<string>();
  allArtifactRows = [
    ...artifactRowsFromClassification,
    ...knownArtifacts,
  ].filter((row) => {
    const key = `${row.version}::${row.name}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  // Determine environment type.
  const anyFailed = checks.some((c) => !c.passed);
  const hasArtifacts = allArtifactRows.length > 0
    || dupeNames.length > 0
    || dupeVersions.length > 0
    || classified.length > 0;
  const missingAnchors = submittedAnchorCount === 0;

  let environmentType: EnvironmentType;
  if (!anyFailed) {
    environmentType = 'clean_mirror';
  } else if (hasArtifacts) {
    environmentType = 'soak_artifact';
  } else if (missingAnchors) {
    environmentType = 'fixture_seeded';
  } else {
    // Prod divergence only, no artifacts — still classify as soak_artifact.
    environmentType = 'soak_artifact';
  }

  return {
    environment_type: environmentType,
    staging_project_ref: projectRef,
    timestamp: new Date().toISOString(),
    checks,
    artifact_rows: allArtifactRows,
    missing_from_staging: divergence.missingFromStaging,
    extra_vs_prod: divergence.extraVsProd,
  };
}

