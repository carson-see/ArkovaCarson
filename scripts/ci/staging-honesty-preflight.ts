export async function queryManagementApi(projectRef: string, managementApiToken: string, query: string): Promise<Record<string, unknown>[]> {
  const response = await fetch(`${MANAGEMENT_API_BASE_URL}/projects/${encodeURIComponent(projectRef)}/database/query/read-only`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${managementApiToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ query }),
    signal: AbortSignal.timeout(MANAGEMENT_API_TIMEOUT_MS),
  });

  if (!response.ok) {
    throw new Error(`Supabase Management API query failed (${response.status})`);
  }

  const payload = await response.json() as unknown;
  if (!Array.isArray(payload)) {
    throw new Error('Supabase Management API query returned a non-array payload.');
  }
  return payload.filter((row): row is Record<string, unknown> => row !== null && typeof row === 'object' && !Array.isArray(row));
}

async function fetchMigrationRowsViaManagementApi(projectRef: string, managementApiToken: string): Promise<MigrationRow[]> {
  const rows = await queryManagementApi(projectRef, managementApiToken, MIGRATION_LEDGER_QUERY);
  return mapManagementMigrationRows(rows);
}

async function fetchMigrationVersionsViaManagementApi(projectRef: string, managementApiToken: string): Promise<string[]> {
  const rows = await queryManagementApi(projectRef, managementApiToken, MIGRATION_VERSION_QUERY);
  return mapManagementMigrationVersions(rows);
}

async function fetchProdFactsViaManagementApi(projectRef: string, managementApiToken: string): Promise<ProdFactsData> {
  const [cronRows, functionRows] = await Promise.all([
    queryManagementApi(projectRef, managementApiToken, CRON_JOB_NAMES_QUERY),
    queryManagementApi(projectRef, managementApiToken, REFRESH_FUNCTION_EXISTS_QUERY),
  ]);
  return mapManagementProdFacts(cronRows, functionRows);
}

/**
 * Read the canonical migration versions from supabase/migrations/*.sql.
 * This is the repo source of truth the divergence verdict reconciles against.
 * Returns undefined (so buildReport falls back to legacy strictness) if the
 * directory cannot be read.
 */
function loadRepoMigrationVersions(): ReadonlySet<string> | undefined {
  const migrationsDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'supabase', 'migrations');
  try {
    const versions = new Set<string>();
    for (const file of readdirSync(migrationsDir)) {
      if (!file.endsWith('.sql') || file.startsWith('_')) continue;
      const version = parseRepoMigrationVersion(file);
      if (version) versions.add(version);
    }
    return versions.size > 0 ? versions : undefined;
  } catch {
    return undefined;
  }
}

/**
 * The narrow slice of a Supabase client queryOrgTopology needs. Structural, so
 * the helper does not have to name supabase-js's generic client type — which
 * varies with the schema type parameters and does not unify across call sites.
 */
interface OrgProjectionReader {
  from(table: string): {
    select(columns: string): PromiseLike<{
      data: unknown;
      error: { message: string } | null;
    }>;
  };
}

/**
 * Check 7's data, or the reason it could not be read.
 *
 * FD-PREFLIGHT-1: this used to select a column `organizations.name` that does
 * not exist. PostgREST answered 42703, the caller's `if (!error && data)` guard
 * fell through with no else, and the check silently disappeared from the report
 * — for every rig, indefinitely. Every branch here now yields either data or a
 * reason, and the caller turns a reason into a FAILED check.
 */
async function queryOrgTopology(
  publicClient: OrgProjectionReader,
): Promise<{ orgTopology?: OrgTopologyData; orgTopologyError?: string }> {
  try {
    const { data, error } = await publicClient
      .from('organizations')
      .select(ORG_NAME_COLUMNS.join(','));
    if (error) return { orgTopologyError: error.message };
    if (!data) return { orgTopologyError: 'organizations projection returned no rows payload.' };
    const rows = data as unknown as OrgNameRow[];
    return { orgTopology: { totalOrgs: rows.length, seedOrgs: rows.filter(isOrgRowSeeded).length } };
  } catch (err) {
    return { orgTopologyError: err instanceof Error ? err.message : String(err) };
  }
}

/**
 * Check 8 fallback: read pg_cron jobs from the environment under test when no
 * prod ref + Management API token were supplied. Returns undefined when the
 * `cron` schema is not exposed via PostgREST, which is the common case and is
 * why Check 8 stays optional (unlike Check 7 — see queryOrgTopology).
 */
async function queryCronFactsFromEnvironment(
  supabaseUrl: string,
  serviceRoleKey: string,
): Promise<ProdFactsData | undefined> {
  try {
    const cronClient = createClient(supabaseUrl, serviceRoleKey, { db: { schema: 'cron' } });
    const { data, error } = await cronClient.from('job').select('jobname');
    if (error || !data) return undefined;
    const cronJobNames = data.map((j: { jobname: string }) => j.jobname);
    return { cronJobNames, functionExists: cronJobNames.length > 0 };
  } catch {
    return undefined;
  }
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));

  const projectRef = args.projectRef ?? process.env.STAGING_PROJECT_REF;
  const prodProjectRef = args.prodProjectRef ?? process.env.PROD_PROJECT_REF;
  const serviceRoleKey = args.serviceRoleKey ?? process.env.SUPABASE_SERVICE_ROLE_KEY;
  const managementApiToken = args.managementApiToken
    ?? process.env.SUPABASE_ACCESS_TOKEN
    ?? process.env.SUPABASE_MANAGEMENT_API_TOKEN;
  const supabaseUrl = args.supabaseUrl
    ?? (projectRef ? `https://${projectRef}.supabase.co` : undefined);

  if (!supabaseUrl) {
    console.error('::error::Missing --project-ref / STAGING_PROJECT_REF or --supabase-url.');
    process.exit(1);
  }
  if (!serviceRoleKey) {
    console.error('::error::Missing --service-role-key / SUPABASE_SERVICE_ROLE_KEY.');
    process.exit(1);
  }

  const client = createClient(supabaseUrl, serviceRoleKey, {
    db: { schema: 'supabase_migrations' },
  });

  // Query migration rows.
  const { data: migrationData, error: migrationError } = await client
    .from('schema_migrations')
    .select('version, name')
    .order('version', { ascending: true });

  let migrationRows: MigrationRow[];
  if (migrationError) {
    if (isSupabaseMigrationsSchemaUnavailable(migrationError) && managementApiToken && projectRef) {
      migrationRows = await fetchMigrationRowsViaManagementApi(projectRef, managementApiToken);
    } else {
      const hint = isSupabaseMigrationsSchemaUnavailable(migrationError)
        ? ' Set --management-api-token or SUPABASE_ACCESS_TOKEN to query the ledger through the Supabase Management API.'
        : '';
      console.error(`::error::Failed to query schema_migrations: ${migrationError.message}${hint}`);
      process.exit(1);
    }
  } else {
    migrationRows = mapManagementMigrationRows(migrationData ?? []);
  }

  // Query SUBMITTED anchor count.
  const publicClient = createClient(supabaseUrl, serviceRoleKey);
  const { count, error: anchorError } = await publicClient
    .from('anchors')
    .select('*', { count: 'exact', head: true })
    .eq('status', 'SUBMITTED');

  if (anchorError) {
    console.error(`::error::Failed to query anchors: ${anchorError.message}`);
    process.exit(1);
  }

  // Check 7. Every failure path records a reason, so the check is reported as
  // FAILED instead of vanishing from the report — FD-PREFLIGHT-1.
  const { orgTopology, orgTopologyError } = await queryOrgTopology(publicClient);

  let prodVersions = args.prodVersions;
  if (managementApiToken && prodProjectRef) {
    try {
      prodVersions = await fetchMigrationVersionsViaManagementApi(prodProjectRef, managementApiToken);
    } catch {
      console.error('::error::Failed to query prod migration ledger via Management API; refusing to use configured/default prod versions as live prod evidence.');
      process.exit(1);
    }
  }

  // Prod facts: prefer CLI flag, then prod Management API, then environment cron schema.
  let prodFacts: ProdFactsData | undefined = args.prodFacts;
  if (!prodFacts && managementApiToken && prodProjectRef) {
    try {
      prodFacts = await fetchProdFactsViaManagementApi(prodProjectRef, managementApiToken);
    } catch {
      console.error('::error::Failed to query prod facts via Management API; refusing to use staging cron data as prod evidence.');
      process.exit(1);
    }
  }
  if (!prodFacts && !(managementApiToken && prodProjectRef)) {
    prodFacts = await queryCronFactsFromEnvironment(supabaseUrl, serviceRoleKey);
  }

  const repoVersions = loadRepoMigrationVersions();

  const report = buildReport({
    projectRef: projectRef ?? supabaseUrl,
    migrationRows,
    submittedAnchorCount: count ?? 0,
    prodVersions,
    repoVersions,
    orgTopology,
    orgTopologyError,
    prodFacts,
  });

  if (args.format === 'text') {
    process.stdout.write(formatText(report));
  } else {
    console.log(JSON.stringify(report, null, 2));
  }

  const allPassed = report.checks.every((c) => c.passed);
  if (allPassed) {
    if (args.format !== 'json') {
      console.log('All checks passed — staging environment is clean.');
    }
  } else {
    process.exit(1);
  }
}

