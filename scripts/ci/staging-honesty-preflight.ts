/**
 * Classify a single migration row. Returns null if the row looks canonical,
 * or an ArtifactClassification describing why it is suspect.
 */
export function classifyMigrationRow(row: MigrationRow): ArtifactClassification | null {
  const { version, name } = row;

  // Only the canonical init/baseline rows get the init-version exemption.
  if (version === CANONICAL_INIT_VERSION && CANONICAL_INIT_NAMES.has(name)) return null;

  // Known staging/PR prefixes in name.
  const lowerName = name.toLowerCase();
  for (const prefix of STAGING_NAME_PREFIXES) {
    if (lowerName.startsWith(prefix)) {
      return { row, reason: `name starts with ${prefix}` };
    }
  }

  if (version === CANONICAL_INIT_VERSION) {
    return { row, reason: `init version (${version}) with non-canonical name (${name})` };
  }

  // Timestamp-format version (14+ digits, but not a canonical init row).
  if (TIMESTAMP_VERSION_RE.test(version)) {
    return { row, reason: `timestamp version (${version}) — likely preview-branch or staging-only` };
  }

  return null;
}

/**
 * Generic duplicate finder — returns values of `field` that appear more than once.
 */
function findDuplicates(rows: MigrationRow[], field: keyof MigrationRow): string[] {
  const counts = new Map<string, number>();
  for (const row of rows) {
    const val = row[field];
    counts.set(val, (counts.get(val) ?? 0) + 1);
  }
  return [...counts.entries()].filter(([, count]) => count > 1).map(([val]) => val);
}

/**
 * Reconstruct a canonical name identity for a ledger row so that two genuinely
 * distinct migrations whose stored `name` merely dropped its numeric prefix are
 * not mistaken for a duplicate.
 *
 * `supabase db push` records a migration's `name` WITHOUT its numeric prefix
 * (e.g. both `0302_validate_api_key_rpc_hardening` and
 * `0303_validate_api_key_rpc_hardening` collapse to the bare
 * `validate_api_key_rpc_hardening`), while keeping the distinct numeric
 * `version` (0302 vs 0303). Prod, by contrast, stores the prefixed name. Naively
 * counting bare names flags the two distinct migrations as a duplicate on a
 * legitimately-clean isolated rig.
 *
 * Identity rules:
 *  - If the stored `name` already carries a `NNNN_` numeric prefix, the name is
 *    authoritative and used verbatim. This preserves genuine-duplicate detection
 *    (two rows with the SAME prefixed name collide regardless of version) and
 *    keeps contamination signals (a prefixed name whose own prefix disagrees with
 *    its version still collides with the original under the shared prefixed name).
 *  - Otherwise the prefix was dropped on push, so reconstruct `${version}_${name}`
 *    — but only when the row's `version` is a real repo-backed numeric version
 *    (present in `repoVersions`). That guard means two distinct migrations whose
 *    bare names match are separated by their distinct repo-backed versions, while
 *    a non-repo/garbage version cannot manufacture a phantom-distinct identity to
 *    mask a real collision (it falls through to the bare name).
 */
function canonicalNameIdentity(row: MigrationRow, repoVersions?: ReadonlySet<string>): string {
  const { version, name } = row;

  // Name already carries its own numeric prefix → authoritative, use verbatim.
  if (/^\d{4,}_/.test(name)) return name;

  // Bare (prefix-dropped) name: reconstruct identity from the numeric version,
  // but only when that version is a real repo migration. Without a repo set, or
  // for a version the repo does not back, fall back to the bare name so genuine
  // collisions (and contamination) still surface.
  if (version && repoVersions?.has(version)) {
    return `${version}_${name}`;
  }

  return name;
}

/**
 * Find migration names that appear more than once.
 *
 * When `repoVersions` (the repo source-of-truth numeric versions) is supplied,
 * identity is normalized via {@link canonicalNameIdentity} so that two
 * genuinely-distinct migrations whose stored names merely dropped their numeric
 * prefix on `supabase db push` are NOT flagged — while same-version+same-name
 * replays and prefixed-name collisions still are. Returns the stored `name`(s)
 * whose canonical identity collides.
 *
 * Without `repoVersions`, behavior is the legacy bare-name count.
 */
export function findDuplicateNames(rows: MigrationRow[], repoVersions?: ReadonlySet<string>): string[] {
  if (!repoVersions) {
    return findDuplicates(rows, 'name');
  }

  // Count by canonical identity, but report the human-readable stored name.
  const identityCounts = new Map<string, number>();
  const identityToNames = new Map<string, Set<string>>();
  for (const row of rows) {
    const identity = canonicalNameIdentity(row, repoVersions);
    identityCounts.set(identity, (identityCounts.get(identity) ?? 0) + 1);
    let names = identityToNames.get(identity);
    if (!names) {
      names = new Set<string>();
      identityToNames.set(identity, names);
    }
    names.add(row.name);
  }

  const duplicates: string[] = [];
  for (const [identity, count] of identityCounts) {
    if (count > 1) {
      for (const name of identityToNames.get(identity) ?? []) {
        duplicates.push(name);
      }
    }
  }
  return duplicates;
}

/**
 * Find migration versions that appear more than once.
 */
export function findDuplicateVersions(rows: MigrationRow[]): string[] {
  return findDuplicates(rows, 'version');
}

/**
 * Detect rows that match the hardcoded known-artifact list.
 * Also flags duplicate occurrences of KNOWN_DUPLICATE_NAME.
 */
export function detectKnownArtifacts(rows: MigrationRow[]): MigrationRow[] {
  const artifacts: MigrationRow[] = [];

  // Track how many times the known-duplicate name appears.
  let duplicateNameCount = 0;

  for (const row of rows) {
    if (KNOWN_ARTIFACT_NAMES.has(row.name)) {
      artifacts.push(row);
      continue;
    }
    if (row.name === KNOWN_DUPLICATE_NAME) {
      duplicateNameCount++;
      if (duplicateNameCount > 1) {
        // Flag the second (and subsequent) occurrence.
        artifacts.push(row);
      }
    }
  }

  return artifacts;
}

export function isSupabaseMigrationsSchemaUnavailable(
  error: { code?: string; message?: string } | null | undefined,
): boolean {
  const code = error?.code?.toUpperCase();
  const message = error?.message?.toLowerCase() ?? '';
  return code === 'PGRST106'
    || message.includes('schema must be one of')
    || (message.includes('supabase_migrations') && message.includes('invalid schema'));
}

function normalizeMigrationVersion(value: unknown): string | null {
  if (value == null) return null;
  if (typeof value !== 'string' && typeof value !== 'number') return null;
  const raw = String(value).trim();
  if (!raw) return null;
  if (raw === CANONICAL_INIT_VERSION) return raw;
  // Supabase stores canonical short migrations as four-digit strings in prod.
  // Management API numeric rows such as 294 must compare as "0294".
  if (/^\d+$/.test(raw) && raw.length < 14) {
    return raw.padStart(4, '0');
  }
  return raw;
}

function normalizeMigrationName(value: unknown): string {
  if (value == null) return '';
  if (typeof value !== 'string' && typeof value !== 'number') return '';
  return String(value).trim();
}

export function mapManagementMigrationRows(rows: readonly Record<string, unknown>[]): MigrationRow[] {
  return rows.flatMap((row) => {
    const version = normalizeMigrationVersion(row.version);
    if (!version) return [];
    return [{
      version,
      name: normalizeMigrationName(row.name),
    }];
  });
}

export function mapManagementMigrationVersions(rows: readonly Record<string, unknown>[]): string[] {
  return rows.flatMap((row) => {
    const version = normalizeMigrationVersion(row.version);
    return version ? [version] : [];
  });
}

export function mapManagementProdFacts(
  cronRows: readonly Record<string, unknown>[],
  functionRows: readonly Record<string, unknown>[],
): ProdFactsData {
  const cronJobNamesValue = cronRows[0]?.cron_job_names;
  const cronJobNames = Array.isArray(cronJobNamesValue)
    ? cronJobNamesValue.map(String)
    : [];
  return {
    cronJobNames,
    functionExists: isTruthyManagementValue(functionRows[0]?.function_exists),
  };
}

function isTruthyManagementValue(value: unknown): boolean {
  return value === true || value === 'true' || value === 't' || value === '1' || value === 1;
}

/**
 * Compare staging migration versions against the prod ledger.
 */
export function computeProdDivergence(
  rows: MigrationRow[],
  prodVersions: string[],
): { missingFromStaging: string[]; extraVsProd: string[] } {
  const stagingVersions = new Set(rows.map((r) => r.version));
  const prodSet = new Set(prodVersions);

  const missingFromStaging = prodVersions.filter((v) => !stagingVersions.has(v));
  const extraVsProd = [...stagingVersions].filter((v) => !prodSet.has(v));

  return { missingFromStaging, extraVsProd };
}

/**
 * Parse the canonical migration version (the `NNNN_` prefix, or the all-zero
 * baseline prefix) from a migration filename. Mirrors the convention enforced
 * by scripts/ci/check-migration-prefix-uniqueness.ts so the preflight reads the
 * repo the same way the rest of CI does.
 *
 * Returns null for files that carry no numeric prefix (templates, READMEs).
 */
export function parseRepoMigrationVersion(filename: string): string | null {
  // Strip any leading directory component, then match a leading 4+-digit prefix.
  const base = filename.split('/').pop() ?? filename;
  const m = base.match(/^(\d{4,})_/);
  return m ? m[1] : null;
}

/**
 * True when the ledger contains the canonical squashed-baseline row. The
 * baseline row is recognised by EITHER its version or its name matching the
 * canonical init/baseline set (the squash records version `00000000000000`
 * with name `baseline_at_main_HEAD`).
 *
 * Presence of this row means the rig was built from a squashed baseline, so the
 * baseline legitimately subsumes all pre-baseline prod history — those prod rows
 * being "missing" from the rig is expected, not contamination.
 */
export function hasCanonicalBaseline(rows: MigrationRow[]): boolean {
  return rows.some((r) => CANONICAL_INIT_NAMES.has(r.version) || CANONICAL_INIT_NAMES.has(r.name));
}

/**
 * Structured verdict from the repo-files-as-source-of-truth divergence analysis.
 */
export interface ProdDivergenceVerdict {
  /** Rig carries the canonical squashed-baseline row. */
  baselinePresent: boolean;
  /** Rig versions absent from prod AND absent from the repo (potential contamination). MUST FAIL. */
  unexplainedExtras: string[];
  /** Repo migration versions absent from the rig ledger (rig incomplete / behind main). MUST FAIL. */
  missingRepoMigrations: string[];
  /** Prod versions absent from the rig (informational under a baseline squash; failure otherwise). */
  prodMissing: string[];
  /** Overall pass/fail for the prod_divergence check. */
  passed: boolean;
}

/**
 * Baseline-squash-aware divergence analysis.
 *
 * Legitimacy is judged against the repo migration files (the source of truth
 * per §1.2 schema-first) plus the canonical baseline — NEVER the rig's own
 * claims. A clean isolated rig built by squashing pre-baseline history into the
 * canonical baseline and then applying every repo migration is `clean_mirror`,
 * even though its ledger diverges from prod's (prod still carries pre-baseline
 * rows and stores recent migrations under timestamp/descriptive version
 * strings).
 *
 * Buckets (compared by version):
 *  - unexplainedExtras: rig ∉ prod AND rig ∉ repo AND not the canonical baseline.
 *    These are rows nothing in the repo or prod can account for → contamination.
 *  - missingRepoMigrations: repo ∉ rig → the rig is behind the repo / incomplete.
 *  - prodMissing: prod ∉ rig. Informational when a baseline row is present (the
 *    baseline subsumes pre-baseline history); otherwise a failure (this preserves
 *    the old strictness for incremental shared-staging ledgers with no baseline).
 *
 * PASS iff unexplainedExtras and missingRepoMigrations are both empty AND
 * (a baseline is present OR there are no prod-missing rows).
 */
export function analyzeProdDivergence(
  rows: MigrationRow[],
  prodVersions: string[],
  repoVersions: ReadonlySet<string>,
): ProdDivergenceVerdict {
  const rigVersions = new Set(rows.map((r) => r.version));
  const prodSet = new Set(prodVersions);
  const baselinePresent = hasCanonicalBaseline(rows);

  // Rig rows that prod does not have.
  const extras = [...rigVersions].filter((v) => !prodSet.has(v));

  // An extra is "explained" if it corresponds to a repo migration file or is the
  // canonical baseline version. Anything else is unaccounted-for → contamination.
  const unexplainedExtras = extras.filter(
    (v) => !repoVersions.has(v) && !CANONICAL_INIT_NAMES.has(v),
  );

  // Every repo migration must be present in the rig ledger.
  const missingRepoMigrations = [...repoVersions].filter((v) => !rigVersions.has(v));

  // Prod versions the rig lacks.
  const prodMissing = prodVersions.filter((v) => !rigVersions.has(v));

  const passed =
    unexplainedExtras.length === 0 &&
    missingRepoMigrations.length === 0 &&
    (baselinePresent || prodMissing.length === 0);

  return { baselinePresent, unexplainedExtras, missingRepoMigrations, prodMissing, passed };
}

/**
 * Check org topology: distinguish single-tenant prod from multi-org staging seeds.
 * Requires org-scoped fixtures (non-seed orgs) when seed orgs are present.
 */
export function checkOrgTopology(data: OrgTopologyData): CheckResult {
  if (data.totalOrgs === 0) {
    return {
      name: 'org_topology',
      passed: false,
      details: 'No organizations found — staging lacks seed data.',
    };
  }

  if (data.seedOrgs === 0) {
    return {
      name: 'org_topology',
      passed: true,
      details: `${data.totalOrgs} org(s), no staging seed orgs — prod-like single-tenant topology.`,
    };
  }

  const fixtureOrgs = data.totalOrgs - data.seedOrgs;
  if (fixtureOrgs > 0) {
    return {
      name: 'org_topology',
      passed: true,
      details: `${data.totalOrgs} org(s) total (${data.seedOrgs} seed, ${fixtureOrgs} org-scoped fixture(s)).`,
    };
  }

  return {
    name: 'org_topology',
    passed: false,
    details: `All ${data.totalOrgs} org(s) are seed-prefixed — no org-scoped fixtures for connector work.`,
  };
}

/**
 * Verify prod facts from the 2026-05-06 correction:
 *   - pg_cron has vacuum-anchors job
 *   - refresh_pipeline_dashboard_cache() exists
 *   - refresh-pipeline-dashboard-cache is scheduled per the SCRUM-1708 cadence
 */
export function checkProdFacts(data: ProdFactsData): CheckResult {
  const issues: string[] = [];

  if (!data.cronJobNames.includes('vacuum-anchors')) {
    issues.push('pg_cron vacuum-anchors job missing');
  }

  if (!data.functionExists) {
    issues.push('refresh_pipeline_dashboard_cache() function missing');
  }

  if (!data.cronJobNames.includes('refresh-pipeline-dashboard-cache')) {
    issues.push('refresh-pipeline-dashboard-cache job missing');
  }

  return {
    name: 'prod_facts',
    passed: issues.length === 0,
    details: issues.length === 0
      ? 'Prod facts verified: vacuum-anchors scheduled, refresh_pipeline_dashboard_cache exists, refresh-pipeline-dashboard-cache scheduled.'
      : `Prod facts divergence: ${issues.join('; ')}.`,
  };
}

/**
 * Classify an org name as a staging seed org (case-insensitive prefix match).
 */
export function isOrgSeedName(name: string): boolean {
  const lower = name.toLowerCase();
  return SEED_ORG_PREFIXES.some((p) => lower.startsWith(p));
}

/**
 * True when EITHER org-name column carries a staging seed prefix.
 *
 * Both columns are considered because a rig can be seeded with a real-looking
 * `legal_name` and a `stg`-prefixed `display_name`, or the reverse.
 */
export function isOrgRowSeeded(row: OrgNameRow): boolean {
  return ORG_NAME_COLUMNS.some((column) => {
    const value = row[column];
    return typeof value === 'string' && isOrgSeedName(value);
  });
}

